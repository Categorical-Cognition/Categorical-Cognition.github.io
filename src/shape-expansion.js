const pendingExpansions = new WeakMap();

export function shapeExpansionEligibility(store, objectId) {
  if (!store?.hasSelectableSimplex(objectId)) {
    return { allowed: false, reason: "Select an existing object to attach a golog." };
  }
  if (store.spheres.has(objectId) || store.structure?.id === CORE_THETA_STRUCTURE_ID) {
    return { allowed: true, reason: "" };
  }
  return {
    allowed: false,
    reason: "Nested gologs are supported on nodes and Theta shapes; virtual arrows and cells are not supported.",
  };
}

// An expansion boundary is the subpresheaf generated by its owner. The chosen
// target root determines every restriction; repeated faces must have one image.
export function deriveShapeRestrictionMap(source, objectId, target, rootObjectId) {
  if (source.category !== target.category) throw new Error("Expansion gologs must share their boundary category");
  const mapping = new Map();
  const reverse = new Map();
  const queue = [[objectId, rootObjectId]];
  for (let i = 0; i < queue.length; i++) {
    const [sourceId, targetId] = queue[i];
    const element = source.get(sourceId);
    const image = target.get(targetId);
    if (element.shape !== image.shape) throw new Error(`Expansion root or boundary changes shape: ${sourceId}`);
    if (mapping.has(sourceId)) {
      if (mapping.get(sourceId) !== targetId) throw new Error(`Expansion does not preserve shared boundary: ${sourceId}`);
      continue;
    }
    if (reverse.has(targetId) && reverse.get(targetId) !== sourceId) {
      throw new Error(`Expansion merges distinct boundary objects: ${sourceId}`);
    }
    mapping.set(sourceId, targetId);
    reverse.set(targetId, sourceId);
    for (const arrow of source.category.incoming(element.shape)) {
      queue.push([element.faces[arrow.id], image.faces[arrow.id]]);
    }
  }
  const closure = new FinitePresheaf(source.category, [...mapping.keys()].map((id) => source.get(id)));
  return naturalTransformation(closure, target, Object.fromEntries(mapping));
}

function expansionDetails(workspace, store, objectId, payload) {
  if (!store.hasSelectableSimplex(objectId)) throw new Error(`Expansion owner does not exist: ${objectId}`);
  const targetGolog = workspace?.gologs.get(payload.targetGologId);
  if (workspace && !targetGolog) throw new Error(`Nested golog target does not exist: ${payload.targetGologId}`);
  if (store.spheres.has(objectId) && !payload.rootObjectId) {
    return { payload, boundaryMap: [], shape: null };
  }
  if (!targetGolog) throw new Error("A rooted expansion requires a workspace and target golog");
  if (store.structure?.id !== CORE_THETA_STRUCTURE_ID || targetGolog.state.structure?.id !== CORE_THETA_STRUCTURE_ID) {
    throw new Error("Rooted shape expansions require hierarchical Theta gologs");
  }
  const source = store.getPresheaf();
  const target = targetGolog.state.getPresheaf();
  const shape = source.get(objectId).shape;
  let rootObjectId = payload.rootObjectId;
  let mapping;
  if (rootObjectId) {
    if (!targetGolog.state.hasSelectableSimplex(rootObjectId)) throw new Error(`Expansion target root does not exist: ${rootObjectId}`);
    mapping = deriveShapeRestrictionMap(source, objectId, target, rootObjectId);
  } else {
    const candidates = target.at(shape).filter(({ id }) => targetGolog.state.hasSelectableSimplex(id)).flatMap(({ id }) => {
      try { return [{ id, mapping: deriveShapeRestrictionMap(source, objectId, target, id) }]; }
      catch { return []; }
    });
    if (candidates.length !== 1) throw new Error(candidates.length
      ? "Expansion target has ambiguous roots; provide rootObjectId"
      : "Expansion target has no compatible root; provide a boundary-preserving rootObjectId");
    rootObjectId = candidates[0].id;
    mapping = candidates[0].mapping;
  }
  return {
    payload: { ...payload, rootObjectId }, shape,
    boundaryMap: Object.entries(mapping).map(([sourceObjectId, targetObjectId]) => ({
      source: { gologId: store.gologId, objectId: sourceObjectId },
      target: { gologId: targetGolog.id, objectId: targetObjectId },
      shape: source.get(sourceObjectId).shape,
      derived: !store.hasSelectableSimplex(sourceObjectId),
      root: sourceObjectId === objectId,
    })),
  };
}

export function normalizeShapeExpansionPayload(workspace, store, objectId, payload) {
  return expansionDetails(workspace, store, objectId, normalizePayload(payload)).payload;
}

export function inspectShapeExpansion(workspace, request = {}) {
  const gologId = request.gologId ?? workspace.activeGologId;
  const golog = workspace.gologs.get(gologId);
  if (!golog) throw new Error(`Golog does not exist: ${gologId}`);
  const objectId = String(request.objectId ?? "");
  if (!golog.state.hasSelectableSimplex(objectId)) throw new Error(`Expansion owner does not exist: ${objectId}`);
  const payload = request.targetGologId
    ? normalizePayload({ type: PAYLOAD_TYPES.NESTED_GOLOG, targetGologId: request.targetGologId, rootObjectId: request.rootObjectId })
    : golog.state.getPayloadByType(objectId, PAYLOAD_TYPES.NESTED_GOLOG);
  if (!payload) return { gologId, objectId, attached: false, boundaryMap: [] };
  const details = expansionDetails(workspace, golog.state, objectId, payload);
  return { gologId, objectId, attached: true, targetGologId: details.payload.targetGologId,
    rootObjectId: details.payload.rootObjectId ?? null, shape: details.shape,
    boundaryMap: details.boundaryMap };
}

function apply(store, type, payload) {
  const result = store.operationPipeline.submit(type, payload, { origin: { source: "structured-creation-service", role: "system" } });
  const validate = (settled) => {
    if (!settled.ok || settled.pending) throw new Error(`Expansion operation rejected: ${settled.reason ?? type}`);
    return settled;
  };
  return result?.then ? Promise.resolve(result).then(validate) : validate(result);
}

function sequence(actions, index = 0) {
  for (let i = index; i < actions.length; i++) {
    const result = actions[i]();
    if (result?.then) return Promise.resolve(result).then(() => sequence(actions, i + 1));
  }
}

export function createShapeExpansion(app, request = {}) {
  const workspace = app.workspace;
  const gologId = request.gologId ?? workspace.activeGologId;
  const parent = workspace.gologs.get(gologId);
  const objectId = String(request.objectId ?? "");
  if (!parent?.state.hasSelectableSimplex(objectId)) throw new Error(`Expansion owner does not exist: ${gologId}/${objectId}`);
  const pendingKey = `${gologId}\u0000${objectId}`;
  const pendingForWorkspace = pendingExpansions.get(workspace);
  const existingPending = pendingForWorkspace?.get(pendingKey);
  if (existingPending) return existingPending.then((result) => {
    if (request.activate) workspace.activateGolog(result.targetGologId);
    return { ...result, created: false };
  });
  const existing = parent.state.getPayloadByType(objectId, PAYLOAD_TYPES.NESTED_GOLOG);
  if (existing) {
    const result = inspectShapeExpansion(workspace, { gologId, objectId });
    if (request.activate) workspace.activateGolog(result.targetGologId);
    return { ...result, created: false };
  }
  const eligibility = shapeExpansionEligibility(parent.state, objectId);
  if (!eligibility.allowed) throw new Error(eligibility.reason);
  const owner = parent.state.getObject(objectId);
  const options = { title: request.title ?? `${owner.name || objectId} expansion`,
    structureId: parent.structure.id, schema: parent.structure.schema, activate: false };
  const child = app.createGolog ? app.createGolog(options) : workspace.createGolog(options);
  let rootObjectId = null;
  let publishedFingerprint = null;
  const cleanup = (error) => {
    // Every submitted operation has settled before rollback. An accepted parent
    // attachment must retain its target even if later inspection fails.
    const currentParent = workspace.gologs.get(gologId) ?? parent;
    if (currentParent.state.getPayloadByType(objectId, PAYLOAD_TYPES.NESTED_GOLOG)?.targetGologId === child.id) throw error;
    const blocked = (failure) => {
      const reason = String(failure.message ?? failure);
      throw new Error(`${error.message}; ${reason.startsWith("Publication cleanup blocked:")
        ? reason : `Publication cleanup blocked: ${reason}`}`, { cause: error });
    };
    const removeLocal = () => {
      if (publishedFingerprint !== null) return retractGologPublication(workspace, child.id, publishedFingerprint, {
        deleteGolog: app.deleteGolog ? (gologId) => app.deleteGolog(gologId) : undefined,
      }).then(() => { throw error; }, blocked);
      if (app.deleteGolog) app.deleteGolog(child.id);
      else workspace.deleteGolog(child.id);
      throw error;
    };
    let retraction;
    try {
      if (publishedFingerprint !== null) assertGologPublicationRetractionAllowed(workspace, child.id, publishedFingerprint);
      retraction = workspace.gologs.has(child.id) ? workspace.retractGolog?.(child.id) : null;
    }
    catch (failure) { return blocked(failure); }
    return retraction?.then ? retraction.then(removeLocal, blocked) : removeLocal();
  };
  const trackPending = (result) => {
    if (!result?.then) return result;
    const pendingByOwner = pendingForWorkspace ?? new Map();
    pendingExpansions.set(workspace, pendingByOwner);
    const completed = result.finally(() => {
      if (pendingByOwner.get(pendingKey) === completed) pendingByOwner.delete(pendingKey);
    });
    pendingByOwner.set(pendingKey, completed);
    return completed;
  };
  try {
    const actions = [];
    if (!parent.state.spheres.has(objectId)) {
      const source = parent.state.getPresheaf();
      const closure = new Set(Object.keys(deriveShapeRestrictionMap(source, objectId, source, objectId)));
      const definition = structureDefinitionFor(parent.structure.id);
      const elements = definition.serializeElements(parent.state).filter(({ id }) => closure.has(id))
        .map((element) => definition.normalizeSerializedElement(element, {
          vectorFromArray: (value) => value?.clone?.() ?? new THREE.Vector3(...value),
          vector2FromArray: (value) => value?.clone?.() ?? new THREE.Vector2(...value),
        }));
      // Keep local native ids so repeated faces remain shared. Private horizontal
      // restrictions are generated afresh from the copied root, never serialized.
      elements.sort((a, b) => a.dimension - b.dimension);
      for (const element of elements) actions.push(() => apply(child.state, "element:create", definition.creationPayload(element)));
      for (const element of elements) {
        for (const payload of parent.state.getPayloads(element.id)) {
          if (element.id === objectId && payload.type === PAYLOAD_TYPES.NESTED_GOLOG) continue;
          actions.push(() => apply(child.state, "payload:typed-add", { id: element.id, payload }));
        }
      }
      rootObjectId = objectId;
    }
    actions.push(() => {
      publishedFingerprint = publicationFingerprint(gologPublication(workspace, child.id));
      return workspace.publishGolog?.(child.id);
    });
    actions.push(() => {
      // A publication acknowledgement can arrive with a hydrated workspace.
      // Resolve its current store instead of mutating the pre-publication owner.
      const currentParent = workspace.gologs.get(gologId);
      if (!currentParent) throw new Error(`Expansion owner golog disappeared: ${gologId}`);
      return apply(currentParent.state, "payload:golog-attach", { id: objectId, targetGologId: child.id, rootObjectId });
    });
    const finish = () => {
      if (request.activate) workspace.activateGolog(child.id);
      return { ...inspectShapeExpansion(workspace, { gologId, objectId }), created: true };
    };
    const pending = sequence(actions);
    return pending?.then ? trackPending(pending.then(finish).catch(cleanup)) : finish();
  } catch (error) {
    return trackPending(cleanup(error));
  }
}

export function assertShapeExpansionDeletionAllowed(store, objectId) {
  if (!store.workspace || !store.hasSelectableSimplex(objectId)) return;
  const removed = new Set(store.getPresheaf().support([objectId]).map(({ id }) => id));
  for (const golog of store.workspace.gologs.values()) {
    for (const [ownerId] of golog.state.payloadAttachments) {
      const payload = golog.state.getPayloadByType(ownerId, PAYLOAD_TYPES.NESTED_GOLOG);
      if (payload?.targetGologId !== store.gologId || !payload.rootObjectId ||
        (golog.id === store.gologId && removed.has(ownerId))) continue;
      const details = expansionDetails(store.workspace, golog.state, ownerId, payload);
      if (details.boundaryMap.some(({ target }) => removed.has(target.objectId))) {
        throw new Error(`Object belongs to expansion boundary of ${golog.id}/${ownerId}; detach that expansion first`);
      }
    }
  }
}

export function assertShapeExpansionBoundaryEditAllowed(store, objectId) {
  if (!store.workspace) return;
  for (const golog of store.workspace.gologs.values()) {
    for (const [ownerId] of golog.state.payloadAttachments) {
      const payload = golog.state.getPayloadByType(ownerId, PAYLOAD_TYPES.NESTED_GOLOG);
      if (!payload?.rootObjectId || (golog.id !== store.gologId && payload.targetGologId !== store.gologId)) continue;
      const details = expansionDetails(store.workspace, golog.state, ownerId, payload);
      if (details.boundaryMap.some(({ source, target }) =>
        (source.gologId === store.gologId && source.objectId === objectId) ||
        (target.gologId === store.gologId && target.objectId === objectId))) {
        throw new Error(`Object belongs to expansion boundary of ${golog.id}/${ownerId}; detach that expansion before changing its boundary`);
      }
    }
  }
}

// Run on normalized records before hydration clears the current workspace.
export function validateWorkspaceShapeExpansions(records, attachments) {
  const workspace = { gologs: new Map(records.map((record) => {
    const ids = new Set(record.elements.map(({ id }) => id));
    let snapshot;
    const state = { gologId: record.id, structure: record.structure,
      spheres: new Set(record.elements.filter(({ dimension }) => dimension === 0).map(({ id }) => id)),
      hasSelectableSimplex: (id) => ids.has(id),
      getPresheaf: () => snapshot ??= presheafFromElements(record.structure.id, record.elements) };
    return [record.id, { id: record.id, state }];
  })) };
  for (const attachment of attachments) {
    if (attachment.payload.type !== PAYLOAD_TYPES.NESTED_GOLOG) continue;
    const state = workspace.gologs.get(attachment.owner.gologId)?.state;
    attachment.payload = normalizeShapeExpansionPayload(workspace, state, attachment.owner.objectId, attachment.payload);
  }
}
